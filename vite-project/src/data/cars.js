export const getCarById = (id) => carsDatabase.find((car) => car.id === Number(id));

export const getCarBySlug = (slug) => carsDatabase.find((car) => car.slug === slug);

export const getCarsByBody = (bodyStyle) =>
  carsDatabase.filter(
    (car) => car.overview.body.toLowerCase() === bodyStyle.toLowerCase()
  );

export const filterCars = ({ body, minPrice, maxPrice, fuel, transmission, condition, make, model, search, sort }) => {
  let list = carsDatabase.filter((car) => {
    if (body && car.overview?.body?.toLowerCase() !== body.toLowerCase()) return false;
    if (minPrice && car.price < minPrice) return false;
    if (maxPrice && car.price > maxPrice) return false;
    if (fuel && car.quickSpecs?.fuel?.toLowerCase() !== fuel.toLowerCase()) return false;
    if (
      transmission &&
      car.quickSpecs?.transmission?.toLowerCase() !== transmission.toLowerCase()
    )
      return false;
    if (condition && car.overview?.condition?.toLowerCase() !== condition.toLowerCase())
      return false;
    if (make) {
      const carName = (car.name || "").toLowerCase();
      if (!carName.includes(make.toLowerCase())) return false;
    }
    if (model) {
      const carName = (car.name || "").toLowerCase();
      if (!carName.includes(model.toLowerCase())) return false;
    }
    if (search) {
      const q = search.toLowerCase();
      const match = (car.name || "").toLowerCase().includes(q) || (car.subtitle || "").toLowerCase().includes(q);
      if (!match) return false;
    }
    return true;
  });

  if (sort === "price-asc") {
    list.sort((a, b) => a.price - b.price);
  } else if (sort === "price-desc") {
    list.sort((a, b) => b.price - a.price);
  } else if (sort === "mileage-asc") {
    list.sort((a, b) => {
      const ma = parseInt(a.quickSpecs?.miles || a.overview?.mileage || "0");
      const mb = parseInt(b.quickSpecs?.miles || b.overview?.mileage || "0");
      return ma - mb;
    });
  } else if (sort === "mileage-desc") {
    list.sort((a, b) => {
      const ma = parseInt(a.quickSpecs?.miles || a.overview?.mileage || "0");
      const mb = parseInt(b.quickSpecs?.miles || b.overview?.mileage || "0");
      return mb - ma;
    });
  }

  return list;
};
